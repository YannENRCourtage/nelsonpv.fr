export const getProcessedTariffData = () => {
  const sortedData = [...tariffData].sort((a, b) => {
    if (a.provider < b.provider) return -1;
    if (a.provider > b.provider) return 1;
    if (a.offer < b.offer) return -1;
    if (a.offer > b.offer) return 1;
    return 0;
  });

  const baseAndHPHC = [];
  const HcHpOffers = {};

  sortedData.forEach(tariff => {
    if (tariff.tariffType === 'Base' || tariff.tariffType === 'Sale') {
      baseAndHPHC.push(tariff);
    } else if (tariff.tariffType === 'HC' || tariff.tariffType === 'HP') {
      const key = `${tariff.provider}|${tariff.offer}|${tariff.power}`;
      if (!HcHpOffers[key]) {
        HcHpOffers[key] = {};
      }
      HcHpOffers[key][tariff.tariffType] = tariff.price;
    }
  });

  for (const key in HcHpOffers) {
    if (HcHpOffers[key].HC && HcHpOffers[key].HP) {
      const [provider, offer, powerStr] = key.split('|');
      const power = parseInt(powerStr);
      
      baseAndHPHC.push({
        provider,
        offer,
        tariffType: 'HP/HC',
        power,
        price: HcHpOffers[key].HP,
      });
    }
  }
  
  const providerOrder = {
    'Alpiq': 1, 'Alterna Énergie': 2, 'CDiscount Energie': 3, 'Chez Switch': 4, 'dyneff': 5, 'EDF': 6,
    'ekWateur': 7, 'Elmy': 8, 'Enercoop': 9, 'Energia': 10, 'Énergie d\'ici': 11, 'énergem': 12,
    'Eni (Plénitude)': 13, 'ENGIE': 14, 'GEG (Yéli)': 15, 'GreenYellow': 16, 'Iberdrola': 17,
    'Ilek': 18, 'La Bellenergie': 19, 'Lucia Energie': 20, 'Mega Energie': 21, 'Mint Energie': 22,
    'OHM Energie': 23, 'Octopus Energy': 24, 'Plüm Énergie': 25, 'Primeo Energie': 26, 'Proxelia': 27,
    'Sélia': 28, 'TotalEnergies': 29, 'Urban Solar Energy': 30, 'Vattenfall': 31, 'Wekiwi': 32,
    'SolarTariff': 33 // Added for sorting consistency
  };

  return baseAndHPHC.sort((a,b) => {
    const orderA = providerOrder[a.provider] || 99;
    const orderB = providerOrder[b.provider] || 99;

    if (orderA !== orderB) {
      return orderA - orderB;
    }
    
    // Fallback for any provider not in the list
    if (a.provider.toLowerCase() < b.provider.toLowerCase()) return -1;
    if (a.provider.toLowerCase() > b.provider.toLowerCase()) return 1;

    if (a.offer < b.offer) return -1;
    if (a.offer > b.offer) return 1;

    // Handle power for range tariffs
    const powerA = typeof a.power === 'object' ? a.power.min : a.power;
    const powerB = typeof b.power === 'object' ? b.power.min : b.power;

    if (powerA < powerB) return -1;
    if (powerA > powerB) return 1;
    return 0;
  });
};